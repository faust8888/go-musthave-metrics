// Command reset generates Reset methods for structs marked with // generate:reset.
//
// Run from the module root:
//
//	go run ./cmd/reset
//
// or pass a directory to scan:
//
//	go run ./cmd/reset /path/to/module
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"
)

const (
	marker     = "generate:reset"
	outputName = "reset.gen.go"
)

func main() {
	start := "."
	if len(os.Args) > 1 {
		start = os.Args[1]
	}
	root, err := filepath.Abs(start)
	if err != nil {
		log.Fatal(err)
	}
	if len(os.Args) <= 1 {
		root = findModuleRoot(root)
	}
	if err := generate(root); err != nil {
		log.Fatal(err)
	}
}

func findModuleRoot(dir string) string {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return dir
		}
		dir = parent
	}
}

func generate(root string) error {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if name == "vendor" || name == "testdata" || name == ".git" || (strings.HasPrefix(name, ".") && path != root) {
			return filepath.SkipDir
		}
		dirs = append(dirs, path)
		return nil
	})
	if err != nil {
		return err
	}

	packages := make([]*pkgContext, 0, len(dirs))
	resetable := make(map[string]map[string]bool) // package name -> type name
	for _, dir := range dirs {
		ctx, err := parsePackage(dir)
		if err != nil {
			return err
		}
		if ctx == nil {
			continue
		}
		packages = append(packages, ctx)
		if resetable[ctx.name] == nil {
			resetable[ctx.name] = make(map[string]bool)
		}
		for _, s := range ctx.structs {
			resetable[ctx.name][s.name] = true
		}
	}

	for _, ctx := range packages {
		ctx.resetable = resetable
		ctx.all = packages
		if err := ctx.write(); err != nil {
			return err
		}
	}
	return nil
}

type structToGen struct {
	name string
	st   *ast.StructType
	file *ast.File
	fset *token.FileSet
}

type pkgContext struct {
	dir       string
	name      string
	fset      *token.FileSet
	defs      map[string]ast.Expr
	structs   []structToGen
	resetable map[string]map[string]bool
	all       []*pkgContext
}

func parsePackage(dir string) (*pkgContext, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	var files []*ast.File
	pkgName := ""
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == outputName {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Join(dir, name), err)
		}
		if strings.HasSuffix(file.Name.Name, "_test") {
			continue
		}
		if pkgName == "" {
			pkgName = file.Name.Name
		} else if file.Name.Name != pkgName {
			continue
		}
		files = append(files, file)
	}
	if len(files) == 0 {
		return nil, nil
	}

	ctx := &pkgContext{
		dir:  dir,
		name: pkgName,
		fset: fset,
		defs: make(map[string]ast.Expr),
	}
	for _, file := range files {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				ctx.defs[ts.Name.Name] = ts.Type
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				if !hasGenerateReset(ts.Doc, gd.Doc) {
					continue
				}
				ctx.structs = append(ctx.structs, structToGen{
					name: ts.Name.Name,
					st:   st,
					file: file,
					fset: fset,
				})
			}
		}
	}
	sort.Slice(ctx.structs, func(i, j int) bool {
		return ctx.structs[i].name < ctx.structs[j].name
	})
	return ctx, nil
}

func hasGenerateReset(groups ...*ast.CommentGroup) bool {
	for _, g := range groups {
		if g == nil {
			continue
		}
		for _, c := range g.List {
			text := strings.TrimSpace(c.Text)
			text = strings.TrimSpace(strings.TrimPrefix(text, "//"))
			if text == marker {
				return true
			}
		}
	}
	return false
}

func (ctx *pkgContext) write() error {
	path := filepath.Join(ctx.dir, outputName)
	if len(ctx.structs) == 0 {
		_ = os.Remove(path)
		return nil
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", ctx.name)

	for _, s := range ctx.structs {
		recv := receiverName(s.name)
		fmt.Fprintf(&b, "func (%s *%s) Reset() {\n", recv, s.name)
		fmt.Fprintf(&b, "if %s == nil {\nreturn\n}\n", recv)
		for _, field := range s.st.Fields.List {
			names := fieldNames(field)
			for _, name := range names {
				resetValue(&b, recv+"."+name, field.Type, ctx, s, nil)
			}
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w\n%s", path, err, b.String())
	}
	return os.WriteFile(path, formatted, 0o644)
}

func fieldNames(field *ast.Field) []string {
	if len(field.Names) == 0 {
		switch t := unparen(field.Type).(type) {
		case *ast.Ident:
			return []string{t.Name}
		case *ast.StarExpr:
			if id, ok := unparen(t.X).(*ast.Ident); ok {
				return []string{id.Name}
			}
			if sel, ok := unparen(t.X).(*ast.SelectorExpr); ok {
				return []string{sel.Sel.Name}
			}
		case *ast.SelectorExpr:
			return []string{t.Sel.Name}
		}
		return nil
	}
	names := make([]string, 0, len(field.Names))
	for _, n := range field.Names {
		if n.Name == "_" {
			continue
		}
		names = append(names, n.Name)
	}
	return names
}

func resetValue(b *bytes.Buffer, expr string, typ ast.Expr, ctx *pkgContext, s structToGen, seen map[string]bool) {
	typ = unparen(typ)
	if seen == nil {
		seen = make(map[string]bool)
	}

	switch t := typ.(type) {
	case *ast.Ident:
		if ctx.isResetable(ctx.name, t.Name) {
			fmt.Fprintf(b, "%s.Reset()\n", expr)
			return
		}
		if z, ok := builtinZero[t.Name]; ok {
			fmt.Fprintf(b, "%s = %s\n", expr, z)
			return
		}
		if def, ok := ctx.defs[t.Name]; ok {
			if seen[t.Name] {
				return
			}
			seen[t.Name] = true
			resetValue(b, expr, def, ctx, s, seen)
			delete(seen, t.Name)
			return
		}
		fmt.Fprintf(b, "%s = *new(%s)\n", expr, t.Name)

	case *ast.StarExpr:
		fmt.Fprintf(b, "if %s != nil {\n", expr)
		if ctx.isResetableExpr(t.X, s.file) {
			fmt.Fprintf(b, "%s.Reset()\n", expr)
		} else {
			resetValue(b, "(*"+expr+")", t.X, ctx, s, seen)
		}
		fmt.Fprintf(b, "}\n")

	case *ast.ArrayType:
		if t.Len == nil {
			fmt.Fprintf(b, "%s = %s[:0]\n", expr, expr)
			return
		}
		fmt.Fprintf(b, "for i := range %s {\n", expr)
		resetValue(b, expr+"[i]", t.Elt, ctx, s, seen)
		fmt.Fprintf(b, "}\n")

	case *ast.MapType:
		fmt.Fprintf(b, "clear(%s)\n", expr)

	case *ast.StructType:
		for _, field := range t.Fields.List {
			for _, name := range fieldNames(field) {
				resetValue(b, expr+"."+name, field.Type, ctx, s, seen)
			}
		}

	case *ast.SelectorExpr:
		pkgName := identName(t.X)
		if pkgName != "" && ctx.isResetable(ctx.importedPkg(s.file, pkgName), t.Sel.Name) {
			fmt.Fprintf(b, "%s.Reset()\n", expr)
			return
		}
		fmt.Fprintf(b, "if r, ok := any(&%s).(interface{ Reset() }); ok {\n", expr)
		fmt.Fprintf(b, "r.Reset()\n")
		fmt.Fprintf(b, "} else {\n")
		fmt.Fprintf(b, "%s = %s{}\n", expr, exprString(s.fset, typ))
		fmt.Fprintf(b, "}\n")

	case *ast.InterfaceType:
		fmt.Fprintf(b, "if resetter, ok := %s.(interface{ Reset() }); ok && %s != nil {\n", expr, expr)
		fmt.Fprintf(b, "resetter.Reset()\n")
		fmt.Fprintf(b, "} else {\n")
		fmt.Fprintf(b, "%s = nil\n", expr)
		fmt.Fprintf(b, "}\n")

	case *ast.ChanType, *ast.FuncType:
		fmt.Fprintf(b, "%s = nil\n", expr)

	default:
		fmt.Fprintf(b, "%s = *new(%s)\n", expr, exprString(s.fset, typ))
	}
}

func (ctx *pkgContext) isResetable(pkgName, typeName string) bool {
	if pkgName == "" {
		pkgName = ctx.name
	}
	return ctx.resetable[pkgName][typeName]
}

func (ctx *pkgContext) isResetableExpr(typ ast.Expr, file *ast.File) bool {
	typ = unparen(typ)
	switch t := typ.(type) {
	case *ast.Ident:
		return ctx.isResetable(ctx.name, t.Name)
	case *ast.SelectorExpr:
		return ctx.isResetable(ctx.importedPkg(file, identName(t.X)), t.Sel.Name)
	case *ast.StarExpr:
		return ctx.isResetableExpr(t.X, file)
	}
	return false
}

func (ctx *pkgContext) importedPkg(file *ast.File, alias string) string {
	for _, spec := range file.Imports {
		path := strings.Trim(spec.Path.Value, `"`)
		if spec.Name != nil {
			if spec.Name.Name == alias {
				return ctx.packageNameForPath(path)
			}
			continue
		}
		if filepath.Base(path) == alias {
			return ctx.packageNameForPath(path)
		}
	}
	return alias
}

func (ctx *pkgContext) packageNameForPath(path string) string {
	slash := filepath.ToSlash(path)
	for _, p := range ctx.all {
		if strings.HasSuffix(filepath.ToSlash(p.dir), slash) || p.name == filepath.Base(path) {
			return p.name
		}
	}
	return filepath.Base(path)
}

func identName(e ast.Expr) string {
	id, ok := unparen(e).(*ast.Ident)
	if !ok {
		return ""
	}
	return id.Name
}

func unparen(e ast.Expr) ast.Expr {
	for {
		p, ok := e.(*ast.ParenExpr)
		if !ok {
			return e
		}
		e = p.X
	}
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var buf strings.Builder
	if fset == nil {
		fset = token.NewFileSet()
	}
	_ = printer.Fprint(&buf, fset, e)
	return buf.String()
}

func receiverName(typeName string) string {
	var b strings.Builder
	for i, r := range typeName {
		if i == 0 || unicode.IsUpper(r) {
			b.WriteRune(unicode.ToLower(r))
		}
	}
	s := b.String()
	if s == "" {
		return "v"
	}
	if token.IsKeyword(s) {
		r, size := utf8.DecodeRuneInString(typeName)
		if r == utf8.RuneError && size == 0 {
			return "v"
		}
		return string(unicode.ToLower(r)) + "v"
	}
	return s
}

var builtinZero = map[string]string{
	"bool":       "false",
	"int":        "0",
	"int8":       "0",
	"int16":      "0",
	"int32":      "0",
	"int64":      "0",
	"uint":       "0",
	"uint8":      "0",
	"uint16":     "0",
	"uint32":     "0",
	"uint64":     "0",
	"uintptr":    "0",
	"float32":    "0",
	"float64":    "0",
	"complex64":  "0",
	"complex128": "0",
	"string":     `""`,
	"byte":       "0",
	"rune":       "0",
	"any":        "nil",
	"error":      "nil",
}
